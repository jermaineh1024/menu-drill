"""Drawing kit for the how-to pictures (wrap, cut, bag).

Every picture is one inline SVG, 320 x 220 user units, looking straight down at the counter unless it says side view.
The guest is at the top of the picture and you are at the bottom.

Motion: each picture is drawn in its END pose, so a still (no script, reduced motion, a printout) shows the finished
move with its arrow. When the page adds class "play" to the picture, parts carrying an animation class start from the
transform in their --from variable and travel to the end pose inside one of three time windows (a, b, c) of a shared
loop, then the moving parts blink out and the loop restarts. Nothing here needs script to be readable.
"""

W, H = 320, 220
GLOVE, GLOVE_SH, GLOVE_LN = "#8FB6E6", "#6C97CE", "#2C4770"
BREAD, BREAD_HI, BREAD_LN = "#D9A76A", "#EBCB9A", "#9B6A33"
PAPER, PAPER_LN = "#FFFFFF", "#AEA796"
PRINT_BG = "#E4EDF8"          # the printed (logo) side of the paper, which ends up on the outside
COUNTER, COUNTER_LN = "#E6ECEF", "#D2DBE0"
RED, INK, MUTED = "#C8102E", "#1B2B44", "#4F6076"
FONT = "Barlow, 'Helvetica Neue', Arial, sans-serif"

# ---------------------------------------------------------------- time windows of the loop (percent of one loop)
WIN = {"a": (8, 34), "b": (38, 62), "c": (66, 84), "ab": (8, 62), "bc": (38, 84), "abc": (8, 84)}
RESET = 95.5   # moving parts snap back here, while the blink has them invisible


def keyframes_css():
    """The shared keyframes. Generated so the windows above are the single source for every timing."""
    out = ["/* how-to pictures: generated by tools/howto.py, do not edit by hand */",
           "@keyframes hw-blink{0%,91%{opacity:1}94%,97%{opacity:0}100%{opacity:1}}"]
    for k, (t0, t1) in WIN.items():
        mid = (t0 + t1) / 2
        out.append(f"@keyframes hw-mv-{k}{{0%,{t0}%{{transform:var(--from)}}{t1}%,{RESET}%{{transform:none}}{RESET + .01}%,100%{{transform:var(--from)}}}}")
        if len(k) == 1:
            on1 = t0 + 5
            out.append(f"@keyframes hw-on-{k}{{0%,{t0}%{{opacity:0}}{on1}%,{RESET}%{{opacity:1}}{RESET + .01}%,100%{{opacity:0}}}}")
            out.append(f"@keyframes hw-off-{k}{{0%,{t0}%{{opacity:1}}{on1}%,{RESET}%{{opacity:0}}{RESET + .01}%,100%{{opacity:1}}}}")
            out.append(f"@keyframes hw-dim-{k}{{0%,{t0}%{{opacity:1}}{t1}%,{RESET}%{{opacity:.4}}{RESET + .01}%,100%{{opacity:1}}}}")
            # the two faces of a flap that flips during this window swap at the middle, when it is edge-on
            out.append(f"@keyframes hw-fe-{k}{{0%,{mid}%{{opacity:0}}{mid + .01}%,{RESET}%{{opacity:1}}{RESET + .01}%,100%{{opacity:0}}}}")
            out.append(f"@keyframes hw-fs-{k}{{0%,{mid}%{{opacity:1}}{mid + .01}%,{RESET}%{{opacity:0}}{RESET + .01}%,100%{{opacity:1}}}}")
            out.append(f"@keyframes hw-pulse-{k}{{0%,{t0}%{{transform:none}}{mid}%{{transform:scale(.88)}}{t1}%,100%{{transform:none}}}}")
            q = (t1 - t0) / 4
            out.append(f"@keyframes hw-saw-{k}{{0%,{t0}%{{transform:none}}{t0 + q}%{{transform:translate(0,-7px)}}{t0 + 2 * q}%{{transform:translate(0,5px)}}{t0 + 3 * q}%{{transform:translate(0,-7px)}}{t1}%,100%{{transform:none}}}}")
    names = ["mv-" + k for k in WIN] + [f"{n}-{k}" for n in ("on", "off", "dim", "fe", "fs", "pulse", "saw") for k in "abc"]
    # the still is the END pose: parts that have left by then are hidden, a hand that has let go is faint
    out.append(".howto-pic [class*='hw-off-']{opacity:0}")
    out.append(".howto-pic [class*='hw-dim-']{opacity:.4}")
    out.append(".howto-pic.play .hw-loop{animation:hw-blink var(--hw-d,5.2s) linear infinite}")
    for n in names:
        out.append(f".howto-pic.play .hw-{n}{{animation:hw-{n} var(--hw-d,5.2s) ease-in-out infinite both}}")
    # proof sheets freeze the loop at a chosen time
    out.append(".howto-pic.freeze .hw-loop,.howto-pic.freeze [class*='hw-']{animation-play-state:paused!important;animation-delay:calc(var(--hw-at,0) * -1s)!important}")
    out.append("@media (prefers-reduced-motion:reduce){.howto-pic.play .hw-loop,.howto-pic.play [class*='hw-']{animation:none!important}}")
    out.append("body.nomotion .howto-pic.play .hw-loop,body.nomotion .howto-pic.play [class*='hw-']{animation:none!important}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- small helpers
def f(v):
    """Compact number for SVG attributes."""
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pts(points):
    return " ".join(f"{f(x)},{f(y)}" for x, y in points)


def g(body, cls=None, frm=None, tr=None, extra=""):
    """A group. cls: animation classes. frm: the --from transform (where the part starts). tr: a static transform."""
    a = ""
    if tr: a += f' transform="{tr}"'
    if cls: a += f' class="{cls}"'
    if frm: a += f' style="--from:{frm}"'
    return f"<g{a}{extra}>{body}</g>"


def about(x, y, body, cls, frm):
    """Animate `body` with its transform origin at (x, y): flips and presses turn around that point."""
    return g(g(g(body, tr=f"translate({f(-x)} {f(-y)})"), cls=cls, frm=frm), tr=f"translate({f(x)} {f(y)})")


def svg(body, label):
    return (f'<svg class="howto-pic" viewBox="0 0 {W} {H}" role="img" aria-label="{label}">'
            f'<rect width="{W}" height="{H}" rx="12" fill="{COUNTER}"/>'
            f'<rect x=".75" y=".75" width="{W - 1.5}" height="{H - 1.5}" rx="11.25" fill="none" stroke="{COUNTER_LN}" stroke-width="1.5"/>'
            f"{body}</svg>")


def label(x, y, t, anchor="start", size=12, color=INK, weight=700, cls=None, halo=COUNTER):
    c = f' class="{cls}"' if cls else ""
    return (f'<text{c} x="{f(x)}" y="{f(y)}" text-anchor="{anchor}" font-family="{FONT}" font-size="{f(size)}" '
            f'font-weight="{weight}" fill="{color}" stroke="{halo}" stroke-width="3.5" stroke-linejoin="round" paint-order="stroke">{t}</text>')


def step_label(x, y, n, t, cls=None, anchor="start"):
    """A numbered callout inside a picture: a small red disc with the count, then the word."""
    c = f' class="{cls}"' if cls else ""
    dx = 0 if anchor == "start" else -(len(t) * 6.4 + 22)
    return (f'<g{c}><circle cx="{f(x + dx + 8)}" cy="{f(y - 4.2)}" r="8" fill="{RED}"/>'
            f'<text x="{f(x + dx + 8)}" y="{f(y)}" text-anchor="middle" font-family="{FONT}" font-size="11.5" font-weight="800" fill="#FFFFFF">{n}</text>'
            + label(x + dx + 21, y, t, "start", 12.5, RED, 700) + "</g>")


def arrow(d, dash=False, w=3, cls=None):
    da = ' stroke-dasharray="6 5"' if dash else ""
    c = f' class="{cls}"' if cls else ""
    return (f'<path{c} d="{d}" fill="none" stroke="{COUNTER}" stroke-width="{w + 3}" stroke-linecap="round" opacity=".9"/>'
            f'<path{c} d="{d}" fill="none" stroke="{RED}" stroke-width="{w}" stroke-linecap="round"{da} marker-end="url(#hw-ah)"/>')


def ticks(x, y, r0=10, r1=17, angles=(200, 230, 310, 340), cls=None):
    """Short red lines around a point: a press or a pop."""
    import math
    c = f' class="{cls}"' if cls else ""
    d = ""
    for a in angles:
        ca, sa = math.cos(math.radians(a)), math.sin(math.radians(a))
        d += f"M{f(x + r0 * ca)} {f(y + r0 * sa)}L{f(x + r1 * ca)} {f(y + r1 * sa)}"
    return f'<path{c} d="{d}" stroke="{RED}" stroke-width="2.4" stroke-linecap="round" fill="none"/>'


# ---------------------------------------------------------------- paper
def paper(points, printed=False, dash=False, op=1, cls=None):
    c = f' class="{cls}"' if cls else ""
    if dash:
        return f'<polygon{c} points="{pts(points)}" fill="none" stroke="{PAPER_LN}" stroke-width="1.4" stroke-dasharray="5 4" stroke-linejoin="round" opacity="{op}"/>'
    fill = PRINT_BG if printed else PAPER
    s = f'<polygon{c} points="{pts(points)}" fill="{fill}" stroke="{PAPER_LN}" stroke-width="1.4" stroke-linejoin="round" opacity="{op}"/>'
    if printed:
        s += f'<polygon{c} points="{pts(points)}" fill="url(#hw-print)" opacity="{op}"/>'
    return s


def shadow_poly(points, dx=0, dy=3, op=.10):
    return f'<polygon points="{pts([(x + dx, y + dy) for x, y in points])}" fill="#0B1A2C" opacity="{op}"/>'


# ---------------------------------------------------------------- the sub, seen from above
def sub_top(x0, y0, x1, y1, cuts=(), shadow=True):
    r = (y1 - y0) / 2
    w, h = x1 - x0, y1 - y0
    s = ""
    if shadow:
        s += f'<rect x="{f(x0 + 1)}" y="{f(y0 + 3.5)}" width="{f(w - 2)}" height="{f(h)}" rx="{f(r)}" fill="#0B1A2C" opacity=".13"/>'
    s += (f'<rect x="{f(x0)}" y="{f(y0)}" width="{f(w)}" height="{f(h)}" rx="{f(r)}" fill="{BREAD}" stroke="{BREAD_LN}" stroke-width="1.4"/>'
          f'<rect x="{f(x0)}" y="{f(y0)}" width="{f(w)}" height="{f(h)}" rx="{f(r)}" fill="url(#hw-grain)"/>'
          f'<rect x="{f(x0 + 12)}" y="{f(y0 + 4.5)}" width="{f(w - 24)}" height="{f(h * .24)}" rx="{f(h * .12)}" fill="{BREAD_HI}" opacity=".55"/>')
    for cx in cuts:
        s += f'<line x1="{f(cx)}" y1="{f(y0 + 1.5)}" x2="{f(cx)}" y2="{f(y1 - 1.5)}" stroke="{BREAD_LN}" stroke-width="2.2" stroke-linecap="round"/>'
    return s


def bundle(x0, y0, x1, y1, seam=True, shadow=True):
    """The sub once paper is around it: a printed tube."""
    r = (y1 - y0) / 2
    w, h = x1 - x0, y1 - y0
    s = ""
    if shadow:
        s += f'<rect x="{f(x0 + 1)}" y="{f(y0 + 3.5)}" width="{f(w - 2)}" height="{f(h)}" rx="{f(r)}" fill="#0B1A2C" opacity=".13"/>'
    s += (f'<rect x="{f(x0)}" y="{f(y0)}" width="{f(w)}" height="{f(h)}" rx="{f(r)}" fill="{PRINT_BG}" stroke="{PAPER_LN}" stroke-width="1.4"/>'
          f'<rect x="{f(x0)}" y="{f(y0)}" width="{f(w)}" height="{f(h)}" rx="{f(r)}" fill="url(#hw-print)"/>'
          f'<rect x="{f(x0 + 10)}" y="{f(y0 + 4)}" width="{f(w - 20)}" height="{f(h * .22)}" rx="{f(h * .11)}" fill="#FFFFFF" opacity=".7"/>')
    if seam:
        s += f'<line x1="{f(x0 + r)}" y1="{f(y1 - 6)}" x2="{f(x1 - r)}" y2="{f(y1 - 6)}" stroke="{PAPER_LN}" stroke-width="1.1" stroke-dasharray="1 0"/>'
    return s


# ---------------------------------------------------------------- hands
# A LEFT hand, palm down, fingers pointing up the page: the thumb is on the right. mirror=True gives the right hand.
_KNUCKLE_Y = -11
_FINGERS = [  # x at the knuckle, length, lean of the tip (flat pose), lean (spread pose): pinky, ring, middle, index
    (-11.2, 18.5, -2.2, -8.5),
    (-3.9, 25.0, -0.9, -3.4),
    (3.5, 27.5, 0.6, 2.2),
    (10.6, 24.0, 2.0, 8.0),
]
_FW = 7.4  # finger width


def _cap(x1, y1, x2, y2, w, color):
    return f'<line x1="{f(x1)}" y1="{f(y1)}" x2="{f(x2)}" y2="{f(y2)}" stroke="{color}" stroke-width="{f(w)}" stroke-linecap="round"/>'


def hand(x, y, rot=0, s=1.0, pose="flat", mirror=False, cls=None, frm=None, cuff=True, ghost=False):
    """pose: flat | spread | curl (fingers bent over something, shorter) | nothumb (flat, thumb tucked under) |
             fist is not used: the videos never ask for one.
       ghost: draw it as a dashed outline only (a hand that is underneath something)."""
    shapes = []  # (kind, args) so the outline pass and the fill pass draw the same silhouette
    lean_i = 3 if pose in ("spread", "roll") else 2
    scale_len = .68 if pose == "curl" else 1.0
    for fx, ln, *leans in _FINGERS:
        lean = leans[lean_i - 2]
        shapes.append(("cap", fx, _KNUCKLE_Y + 2, fx + lean, _KNUCKLE_Y - ln * scale_len, _FW))
    if pose not in ("nothumb", "curl"):
        if pose == "spread":
            shapes.append(("cap", 13.0, 7.5, 28.5, -3.5, 8.6))
        elif pose == "roll":
            shapes.append(("cap", 13.5, 6.0, 21.0, -13.0, 8.6))
        else:
            shapes.append(("cap", 13.0, 8.0, 25.5, -7.5, 8.6))
    shapes.append(("palm",))
    if cuff:
        shapes.append(("wrist",))

    def draw(kind, args, color, grow):
        if kind == "cap":
            x1, y1, x2, y2, w = args
            return _cap(x1, y1, x2, y2, w + grow, color)
        if kind == "palm":
            e = grow / 2
            return f'<rect x="{f(-15.4 - e)}" y="{f(-13.5 - e)}" width="{f(30.8 + 2 * e)}" height="{f(33 + 2 * e)}" rx="{f(11.5 + e)}" fill="{color}"/>'
        e = grow / 2
        return f'<rect x="{f(-10.5 - e)}" y="{f(13 - e)}" width="{f(21 + 2 * e)}" height="{f(19 + 2 * e)}" rx="{f(6 + e)}" fill="{color}"/>'

    if ghost:
        outline = "".join(draw(k, a, GLOVE_LN, 2.8) for k, *a in shapes)
        inner = "".join(draw(k, a, "#FFFFFF", 0.6) for k, *a in shapes)
        body = f'<g opacity=".5">{outline}{inner}</g>'
    else:
        body = "".join(draw(k, a, GLOVE_LN, 2.8) for k, *a in shapes)
        body += "".join(draw(k, a, GLOVE, 0) for k, *a in shapes)
        # finger creases and knuckles: three short lines, enough to read as a hand and not a mitten
        for (fx, ln, *leans), nxt in zip(_FINGERS, _FINGERS[1:]):
            mx = (fx + nxt[0]) / 2
            body += f'<line x1="{f(mx)}" y1="{f(_KNUCKLE_Y - 1)}" x2="{f(mx + (leans[lean_i - 2] + nxt[lean_i]) / 6)}" y2="{f(_KNUCKLE_Y - 9 * scale_len)}" stroke="{GLOVE_SH}" stroke-width="1.1" stroke-linecap="round"/>'
        if cuff:
            body += f'<line x1="-10" y1="24.5" x2="10" y2="24.5" stroke="{GLOVE_SH}" stroke-width="2.2" stroke-linecap="round"/>'
    sx = -s if mirror else s
    inner = g(body, tr=f"translate({f(x)} {f(y)}) rotate({f(rot)}) scale({f(sx)} {f(s)})")
    if cls or frm:
        return g(inner, cls=cls, frm=frm)
    return inner


def thumb(x, y, rot=0, s=1.0, length=17, cls=None, frm=None):
    """Just a thumb lying on top of something (the rest of the hand is underneath)."""
    body = _cap(0, 0, 0, -length, 8.6 + 2.8, GLOVE_LN) + _cap(0, 0, 0, -length, 8.6, GLOVE)
    inner = g(body, tr=f"translate({f(x)} {f(y)}) rotate({f(rot)}) scale({f(s)})")
    return g(inner, cls=cls, frm=frm) if (cls or frm) else inner


def heel(x, y, rot=0, s=1.0):
    """The heel of a hand and its cuff, seen where a hand goes under the end of the sub."""
    body = (f'<rect x="-13" y="-8" width="26" height="24" rx="10" fill="{GLOVE_LN}"/>'
            f'<rect x="-10.5" y="8" width="21" height="20" rx="6" fill="{GLOVE_LN}"/>'
            f'<rect x="-11.6" y="-6.6" width="23.2" height="21.2" rx="8.6" fill="{GLOVE}"/>'
            f'<rect x="-9.1" y="9.4" width="18.2" height="17.2" rx="4.6" fill="{GLOVE}"/>'
            f'<line x1="-8.6" y1="19" x2="8.6" y2="19" stroke="{GLOVE_SH}" stroke-width="2.2" stroke-linecap="round"/>')
    return g(body, tr=f"translate({f(x)} {f(y)}) rotate({f(rot)}) scale({f(s)})")


